"""Aggregate-only reproduction tests for the paper artifacts (no EEG data, no model, no inference, no resampling).

1. Every aggregate snapshot matches its SHA-256 in results/aggregates/MANIFEST.json.
2. Snapshots contain no person/recording identifiers and no roster/per-person keys.
3. The manuscript tables are regenerated byte-identically (frozen Git blob f4ac863b...).
4. All 16 figure files (8 PDF + 8 PNG) are regenerated byte-identically to paper/figures/FIGURE_SHA256.txt.
5. The 29 numerical manuscript claims checked by verify_final_claims_v8r5.py pass.
"""
import hashlib
import importlib.util
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AGG = ROOT / 'results/aggregates'
FROZEN_TABLE_BLOB = 'f4ac863b0130ef5c8c9253d14bbc2e375b550cd9'
PERSON_ID = re.compile(r'\b(?:SC|ST)\d{3,5}[A-Z0-9]*\b')
RESTRICTED = {'per_person', 'per_recording', 'participant_id', 'subject_id', 'recording_id', 'psg_path',
              'hypnogram_path', 'window_id', 'eeg_path', 'person_ids', 'person_id', 'roster', 'predictions',
              'stage_joins', 'per_person_delta', 'persons', 'worst_three'}


def sha256(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def test_snapshots_match_manifest():
    man = json.loads((AGG / 'MANIFEST.json').read_text())
    assert len(man['files']) == 20
    for f in man['files']:
        assert sha256(AGG / f['snapshot']) == f['snapshot_sha256'], f['snapshot']


def test_snapshots_are_aggregate_only():
    for p in AGG.rglob('*.json'):
        text = p.read_text()
        assert not PERSON_ID.search(text), p
        stack = [json.loads(text)]
        while stack:
            n = stack.pop()
            if isinstance(n, dict):
                for k, v in n.items():
                    if k in RESTRICTED:   # only plain counts are allowed under these names
                        assert isinstance(v, (int, float)) and not isinstance(v, bool), (p, k)
                    stack.append(v)
            elif isinstance(n, list):
                stack.extend(n)


def test_tables_reproduce_frozen_blob():
    tex = (ROOT / 'paper/latex/tables_generated.tex').read_bytes()
    assert hashlib.sha1(b'blob %d\0' % len(tex) + tex).hexdigest() == FROZEN_TABLE_BLOB
    r = subprocess.run([sys.executable, str(ROOT / 'scripts/paper/regenerate_tables_v8r2.py')],
                       cwd=ROOT, capture_output=True, text=True)
    assert r.returncode == 0, r.stderr
    assert 'OK: 51 presentation edits reproduced' in r.stdout


def test_figures_reproduce_byte_identical(tmp_path):
    spec = importlib.util.spec_from_file_location('mf', ROOT / 'scripts/paper/make_figures_v8r5.py')
    mf = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mf)
    mf.S.setup()
    J = mf.load()                       # also checks every input snapshot against MANIFEST.json
    for name, fn in mf.FIGS:
        mf.S.save(fn(J), tmp_path, name)
    expected = {}
    for line in (ROOT / 'paper/figures/FIGURE_SHA256.txt').read_text().splitlines():
        digest, name = line.split()
        expected[name] = digest
    produced = {p.name: sha256(p) for p in tmp_path.iterdir()}
    assert len(expected) == 16
    assert produced == expected


def test_numerical_claims():
    r = subprocess.run([sys.executable, str(ROOT / 'scripts/paper/verify_final_claims_v8r5.py')],
                       cwd=ROOT, capture_output=True, text=True)
    assert r.returncode == 0, r.stderr
    out = json.loads(r.stdout)
    assert out['status'] == 'PASS' and out['checks'] == 29
